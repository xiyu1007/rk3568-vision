// ============================================================================
// image_utils.hpp — 图像处理工具（NV12 前处理 + 画框）
// ============================================================================
//
// 提供两个纯手写（不依赖 OpenCV）的图像处理函数：
//   1. nv12ToRgbLetterbox : 把紧密排列的 NV12 转成 RGB 并 letterbox 到模型输入尺寸
//   2. drawBoxesNv12      : 直接在 NV12 上画检测框（写入编码流，供远程展示）
//
// 为什么手写而不依赖 OpenCV？
//   - 技术栈明确不含 OpenCV，减少一个重量级依赖
//   - 低延迟目标下，手写循环无额外开销，且便于学习理解底层像素操作
// ============================================================================

#pragma once

#include <cstdint>

#include "types.hpp"

namespace vision {

// letterbox 缩放信息：把原图等比缩放到模型输入尺寸时产生的缩放比例与填充。
// 后续检测框逆映射（模型坐标 → 原图坐标）需要用到这三个量。
struct LetterboxInfo {
    float scale = 1.0f;   // 缩放比例 = min(dst_w/w, dst_h/h)
    int   pad_x = 0;      // 水平方向灰边填充（像素）
    int   pad_y = 0;      // 垂直方向灰边填充（像素）
};

// ---------------------------------------------------------------------------
// NV12 → RGB，并 letterbox 到 dst_w × dst_h（YOLOv5 前处理）
// ---------------------------------------------------------------------------
// 参数：
//   nv12   : 输入，紧密排列 NV12（Y 平面 + UV 交错平面），尺寸 w×h
//   w, h   : 输入图像宽高
//   rgb    : 输出，RGB888（每像素 3 字节，R/G/B 顺序），尺寸 dst_w×dst_h×3，
//            由调用方预分配
//   dst_w/h: 模型输入尺寸（YOLOv5 固定 640×640）
//   info   : 输出，letterbox 缩放/填充信息，供检测框逆映射
//
// 说明：
//   - letterbox 先等比缩放（保持宽高比）再居中填充灰边（像素值 114，YOLOv5 惯例）
//   - 采样用最近邻（实现简单、速度快）；aarch64 上可用 RGA 硬件做双线性替代
//   - YUV→RGB 采用 BT.601 有限范围（视频标准），与 cv::COLOR_YUV2RGB_NV12 一致
void nv12ToRgbLetterbox(const uint8_t* nv12, int w, int h,
                        uint8_t* rgb, int dst_w, int dst_h,
                        LetterboxInfo& info);

// ---------------------------------------------------------------------------
// 在 NV12 图像上绘制检测框（就地修改）
// ---------------------------------------------------------------------------
// 参数：
//   nv12 : 输入输出，紧密排列 NV12，尺寸 w×h（就地画框）
//   w, h : 图像宽高
//   det  : 检测结果（框坐标基于原图像素坐标系）
//
// 说明：
//   - 在 Y 平面把框的四条边画成高亮（白=255），人眼清晰可见
//   - 色度（UV）保持中性（128），边框呈现灰白色
//   - 不绘制文字标签（文字需要字体位图），标签信息另见日志输出
void drawBoxesNv12(uint8_t* nv12, int w, int h, const DetectResult& det);

} // namespace vision
